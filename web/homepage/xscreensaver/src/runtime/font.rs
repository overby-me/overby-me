use super::fb::{Fb, Gc};

/// Cell size of the compiled-in font, and where its baseline sits.
const CELL_W: i32 = 12;
const CELL_H: i32 = 22;
const ASCENT: i32 = 17;
const DESCENT: i32 = CELL_H - ASCENT;

/// A loaded font: the bitmap above at some whole magnification.
///
/// `XFontStruct` and `XftFont` both port to this, since the hacks only ever ask
/// them for metrics and then draw with them.
#[derive(Clone, Copy, Debug)]
pub struct Font {
    scale: i32,
}

impl Font {
    /// `XLoadQueryFont` / `XftFontOpenName`, as far as it goes: pull a size out
    /// of the name and ignore everything else about it.
    ///
    /// Handles both spellings the hacks use, and takes the first of a
    /// comma-separated list of alternatives the way `load_xft_font_retry` does.
    ///
    /// Which spelling it is decides what the number means, and the two overlap:
    /// an XLFD (`-*-helvetica-bold-r-normal-*-180-*`) gives its size in tenths
    /// of a point, while an Xft name (`OCR A 192`) gives whole ones, so the
    /// same three digits mean eighteen in the first and a hundred and
    /// ninety-two in the second. A leading dash is what tells them apart.
    pub fn load(spec: &str) -> Font {
        let first = spec.split(',').next().unwrap_or(spec);
        let mut size = 0;
        let mut cur = 0;
        for c in first.chars() {
            if let Some(d) = c.to_digit(10) {
                cur = cur * 10 + d as i32;
            } else {
                if cur > 0 {
                    size = cur;
                }
                cur = 0;
            }
        }
        if cur > 0 {
            size = cur;
        }
        if first.starts_with('-') && size >= 100 {
            size /= 10;
        }
        Font::at_size(size)
    }

    /// The font nearest the requested height in pixels.
    pub fn at_size(size: i32) -> Font {
        let scale = ((size + CELL_H / 2) / CELL_H).max(1);
        Font { scale }
    }

    /// `font->ascent`: how far the tallest glyph rises above the baseline.
    pub fn ascent(&self) -> i32 {
        ASCENT * self.scale
    }

    /// `font->descent`: how far a tail drops below it.
    pub fn descent(&self) -> i32 {
        DESCENT * self.scale
    }

    /// Every glyph is the same width, so this is `XTextWidth` of one character.
    pub fn char_width(&self) -> i32 {
        CELL_W * self.scale
    }

    /// What a hack usually wants for line spacing.
    pub fn line_height(&self) -> i32 {
        (ASCENT + DESCENT) * self.scale
    }

    /// `XTextWidth`.
    pub fn text_width(&self, s: &str) -> i32 {
        s.chars().count() as i32 * self.char_width()
    }

    /// One row of one glyph, twelve bits in the top of the returned value.
    /// Anything outside the font's 256 cells draws as blank, which is what an X
    /// server does with a character a font has no glyph for.
    fn row(ch: char, y: i32) -> u16 {
        let c = ch as u32;
        if c > 255 || !(0..CELL_H).contains(&y) {
            return 0;
        }
        GALLANT[(c as i32 * CELL_H + y) as usize]
    }
}

/// The compiled-in glyph table, as bytes.
///
/// This is here for `memscroller`, which scrolls a dump of the program's own
/// memory. A browser tab cannot read its heap the way upstream reads its own
/// `sbrk`, and this is the largest block of the program's own data that a safe
/// Rust program can hand out. It is about eleven kilobytes, which is the same
/// order as the sixty-four upstream clamps itself to when the addresses it gets
/// back look implausible.
pub fn program_bytes() -> Vec<u8> {
    GALLANT.iter().flat_map(|w| w.to_be_bytes()).collect()
}

impl Fb {
    /// `XDrawString`: `x`, `y` is the origin on the baseline, as in X, so the
    /// glyphs are drawn above it.
    pub fn draw_string(&mut self, gc: &Gc, font: &Font, x: i32, y: i32, s: &str) {
        let top = y - font.ascent();
        for (i, ch) in s.chars().enumerate() {
            self.draw_glyph(gc, font, x + i as i32 * font.char_width(), top, ch);
        }
    }

    /// `XDrawImageString`, which unlike `XDrawString` paints the background of
    /// the whole cell first, so it overwrites what was there rather than
    /// drawing through it.
    pub fn draw_image_string(&mut self, gc: &Gc, font: &Font, x: i32, y: i32, s: &str) {
        let mut bg = gc.clone();
        bg.set_foreground(gc.background);
        self.fill_rectangle(
            &bg,
            x,
            y - font.ascent(),
            font.text_width(s),
            font.line_height(),
        );
        self.draw_string(gc, font, x, y, s);
    }

    /// One glyph with its top-left corner at `x`, `y`. Set bits are drawn as
    /// runs so a magnified glyph costs a few rectangles a row rather than one
    /// per pixel.
    fn draw_glyph(&mut self, gc: &Gc, font: &Font, x: i32, y: i32, ch: char) {
        let scale = font.scale;
        for r in 0..CELL_H {
            let bits = Font::row(ch, r);
            if bits == 0 {
                continue;
            }
            let mut c = 0;
            while c < CELL_W {
                if bits & (1 << (15 - c)) == 0 {
                    c += 1;
                    continue;
                }
                let start = c;
                while c < CELL_W && bits & (1 << (15 - c)) != 0 {
                    c += 1;
                }
                self.fill_rectangle(
                    gc,
                    x + start * scale,
                    y + r * scale,
                    (c - start) * scale,
                    scale,
                );
            }
        }
    }
}


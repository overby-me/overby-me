// Upstream writes these to more digits than a `f32` holds, and they are kept
// exactly as it writes them: the point of the tables is that they diff against
// the C, and rounding every literal to the shortest one that round-trips would
// end that. The values are identical either way.
#![allow(clippy::excessive_precision)]

//! The polyhedral models `cubocteversion` deforms between.
//!
//! Each is twelve vertices, and the eversion is the straight line from one to
//! the next: seven of them for Apery's eversion, forty-five for
//! Morin-Denner's. Every one is a position somebody worked out on paper, which
//! is why they are written as arithmetic rather than as decimals, and why the
//! arithmetic is kept.
//!
//! The names beside the rows are upstream's, and are the labels the papers use
//! for the vertices of the cuboctahedron.

/// Vertices, edges and faces in all of the polyhedral models. Twelve, thirty
/// and twenty: the models are triangulated, so the cuboctahedron's eight
/// triangles and six squares arrive as twenty triangles.
pub const NUM_VERT: usize = 12;
pub const NUM_EDGE: usize = 30;
pub const NUM_FACE: usize = 20;

/// Upstream's `M_SQRT2_F`. Its literal and this constant are the same number
/// once rounded to a `f32`.
const SQRT2: f32 = std::f32::consts::SQRT_2;


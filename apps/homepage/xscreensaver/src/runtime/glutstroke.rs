use super::gl::{Glx, Shape};

impl StrokeFont {
    /// The character, or nothing for one the font does not have.
    pub fn char_at(&self, c: char) -> Option<&StrokeChar> {
        let i = c as usize;
        (i < self.chars.len()).then(|| &self.chars[i])
    }

    /// `glutStrokeWidth`: how far along to move after a character.
    pub fn width(&self, c: char) -> f32 {
        self.char_at(c).map(|ch| ch.right).unwrap_or(0.0)
    }

    /// `glutStrokeLength`: how wide a string is.
    pub fn length(&self, s: &str) -> f32 {
        s.chars().map(|c| self.width(c)).sum()
    }

    /// The height of a line of it.
    pub fn line_height(&self) -> f32 {
        self.top - self.bottom
    }
}

/// `glutStrokeCharacter`: draw one character as open polylines, and move the
/// matrix along ready for the next.
pub fn stroke_character(g: &mut Glx, font: &StrokeFont, c: char) {
    let Some(ch) = font.char_at(c) else { return };
    for stroke in ch.strokes {
        g.begin(Shape::LineStrip);
        for p in *stroke {
            g.vertex3f(p[0], p[1], 0.0);
        }
        g.end();
    }
    g.translate(ch.right, 0.0, 0.0);
}

/// The whole string, one character after another.
pub fn stroke_string(g: &mut Glx, font: &StrokeFont, s: &str) {
    for c in s.chars() {
        stroke_character(g, font, c);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Both fonts have the hundred and twenty-eight characters of Latin-1's
    /// lower half, and the printable ones have strokes.
    #[test]
    fn the_fonts_have_their_characters() {
        for font in [&ROMAN, &MONO_ROMAN] {
            assert_eq!(font.chars.len(), 128);
            assert!(font.line_height() > 100.0);
            for c in "ABCXYZabcxyz0189".chars() {
                let ch = font.char_at(c).expect("a missing character");
                assert!(!ch.strokes.is_empty(), "{c} has no strokes");
                assert!(ch.right > 0.0, "{c} has no width");
            }
            // A space has no strokes but does have a width.
            let sp = font.char_at(' ').expect("no space");
            assert!(sp.strokes.is_empty());
            assert!(sp.right > 0.0);
        }
    }

    /// The monospaced one is monospaced and the other one is not.
    #[test]
    fn one_of_them_is_monospaced() {
        let w = MONO_ROMAN.width('i');
        for c in "ABCXYZabcxyz0189".chars() {
            assert_eq!(MONO_ROMAN.width(c), w, "{c} is a different width");
        }
        assert_ne!(ROMAN.width('i'), ROMAN.width('m'), "the roman is fixed");
    }

    /// A drawn character is its polylines, and it leaves the matrix moved
    /// along by its width.
    #[test]
    fn a_character_is_polylines() {
        let mut g = Glx::new();
        g.start_frame(100, 100);
        stroke_character(&mut g, &ROMAN, 'A');
        let f = g.frame();
        assert_eq!(
            f.batches.len(),
            ROMAN.char_at('A').expect("no A").strokes.len(),
            "an A is not its strokes"
        );
        assert!(
            f.vertices
                .iter()
                .all(|v| v.pos[1] >= -40.0 && v.pos[1] <= 120.0),
            "a letter is outside its em"
        );
        // And the string is the sum of its characters.
        assert_eq!(ROMAN.length("AA"), ROMAN.width('A') * 2.0);
    }
}

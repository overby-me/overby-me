/// A thing that is usually still and now and then turns all the way over.
#[derive(Clone, Copy, Default)]
struct Spinner {
    spinning_p: bool,
    /// 0.0 - 1.0
    position: f32,
    /// 0.0 - 1.0, eased in and out
    position_eased: f32,
    /// Portion of the path that is eased. <= 0.5
    easement: f32,
    /// How far along the path, and it may be negative.
    speed: f32,
    /// Relative likelihood of starting to spin.
    probability: f32,
}

/// Smooth curve up, ending at slope = 1.
fn spinner_ease(x: f32) -> f32 {
    ((x / 2.0 + 1.0) * std::f32::consts::PI).cos() + 1.0
}

impl Spinner {
    fn tick(&mut self, speed: f32, button_down: bool) {
        if speed == 0.0 || button_down {
            return;
        }
        if self.spinning_p {
            self.position += self.speed;
            if self.position >= 1.0 || self.position <= 0.0 {
                self.position = 0.0;
                self.position_eased = 0.0;
                self.spinning_p = false;
            } else if self.easement > 0.0 && self.position <= self.easement {
                self.position_eased = self.easement * spinner_ease(self.position / self.easement);
            } else if self.easement > 0.0 && self.position >= 1.0 - self.easement {
                self.position_eased =
                    1.0 - self.easement * spinner_ease((1.0 - self.position) / self.easement);
            } else {
                self.position_eased = self.position;
            }
        } else if self.probability > 0.0
            && random_below((PROBABILITY_SCALE / self.probability) as i32) == 0
        {
            let ss = 0.004;
            self.spinning_p = true;
            self.position = 0.0;
            loop {
                self.speed = speed * (frand(ss / 3.0) + frand(ss / 3.0) + frand(ss / 3.0)) as f32;
                if self.speed > 0.0 {
                    break;
                }
            }
            if random() & 1 != 0 {
                self.speed = -self.speed;
                self.position = 1.0;
            }
        }
    }
}


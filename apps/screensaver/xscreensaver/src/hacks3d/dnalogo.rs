/// `do_normal`: work the normal out from three points of a face and set it.
fn do_normal(g: &mut Gl, a: [f32; 3], b: [f32; 3], c: [f32; 3]) {
    let n = calc_normal(a, b, c);
    g.glx.normal3f(n[0], n[1], n[2]);
}

/// Calculate the angle (in radians) between two vectors.
fn vector_angle(a: [f32; 3], b: [f32; 3]) -> f32 {
    let la = (a[0] * a[0] + a[1] * a[1] + a[2] * a[2]).sqrt();
    let lb = (b[0] * b[0] + b[1] * b[1] + b[2] * b[2]).sqrt();
    if la == 0.0 || lb == 0.0 || a == b {
        return 0.0;
    }
    // avoid fp rounding error (1.000001 => sqrt error)
    let cc = ((a[0] * b[0] + a[1] * b[1] + a[2] * b[2]) / (la * lb)).min(1.0);
    cc.acos()
}

/* Make the helix */

fn make_helix(g: &mut Gl, dc: &Params, facetted: bool, wire: bool) {
    let wall_facets = dc.wall_facets / if facetted { 10 } else { 1 };
    let max_th = std::f32::consts::PI * 2.0 * dc.turns;
    let th_inc = std::f32::consts::PI * 2.0 / wall_facets as f32;

    let (mut x1, mut y1) = (1.0f32, 0.0f32);
    let (mut x1b, mut y1b) = (1.0f32, 0.0f32);
    let (mut x2, mut y2, mut x2b, mut y2b) = (0.0f32, 0.0f32, 0.0f32, 0.0f32);
    let mut z2;
    let mut h2 = 0.0f32;
    let mut h2off = 0.0f32;
    let mut z_inc = dc.turn_spacing / wall_facets as f32;

    let mut th = 0.0f32;
    let mut z1 = -(dc.turn_spacing * dc.turns / 2.0);

    let mut h1 = if dc.wall_taper > 0.0 {
        0.0
    } else {
        dc.wall_height / 2.0
    };
    let mut h1off = if dc.wall_taper > 0.0 {
        -dc.wall_height / 2.0
    } else {
        0.0
    };

    if !dc.clockwise {
        z1 = -z1;
        z_inc = -z_inc;
        h1off = -h1off;
    }

    // Upstream flips the winding four times per facet, and a winding change
    // starts a new draw call, so a three hundred and sixty facet helix would
    // be a thousand of them. The faces are collected by which way they are
    // wound instead and drawn in two runs, which is the same picture in four.
    let mut cw: Vec<([f32; 3], [f32; 3])> = Vec::new();
    let mut ccw: Vec<([f32; 3], [f32; 3])> = Vec::new();
    let mut lines: Vec<[f32; 3]> = Vec::new();

    /* Leading end-cap */
    if !wire && h1 > 0.0 {
        let n = [
            (th + std::f32::consts::FRAC_PI_2).cos(),
            (th + std::f32::consts::FRAC_PI_2).sin(),
            0.0,
        ];
        for p in [
            [x1, y1, z1 - h1 + h1off],
            [x1, y1, z1 + h1 + h1off],
            [x1b, y1b, z1 + h1 + h1off],
            [x1b, y1b, z1 - h1 + h1off],
        ] {
            ccw.push((n, p));
        }
    }

    while th + th_inc <= max_th {
        let mut thick = dc.wall_thickness;

        th += th_inc;

        x2 = th.cos();
        y2 = th.sin();
        z2 = z1 + z_inc;

        h2 = h1;
        h2off = h1off;

        if dc.wall_taper > 0.0 {
            h2off = 0.0;
            if th < dc.wall_taper {
                h2 = dc.wall_height / 2.0
                    * (std::f32::consts::FRAC_PI_2 * (1.0 - (th / dc.wall_taper))).cos();
                h2off = if dc.clockwise {
                    h2 - dc.wall_height / 2.0
                } else {
                    dc.wall_height / 2.0 - h2
                };
                if th + th_inc <= 0.0 {
                    thick = 0.0;
                } else {
                    thick *= (std::f32::consts::FRAC_PI_2 * (1.0 - (th / dc.wall_taper))).cos();
                }
            } else if th >= max_th - dc.wall_taper {
                /* edge case: always come to a point */
                h2 = if th + th_inc > max_th {
                    0.0
                } else {
                    dc.wall_height / 2.0
                        * (std::f32::consts::FRAC_PI_2 * (1.0 - ((max_th - th) / dc.wall_taper)))
                            .cos()
                };
                h2off = if dc.clockwise {
                    dc.wall_height / 2.0 - h2
                } else {
                    h2 - dc.wall_height / 2.0
                };
                if th + th_inc > max_th {
                    thick = 0.0;
                } else {
                    thick *= (std::f32::consts::FRAC_PI_2
                        * (1.0 - ((max_th - th) / dc.wall_taper)))
                        .cos();
                }
            }
        }

        x2b = x2 * (1.0 - thick);
        y2b = y2 * (1.0 - thick);

        let outer = [
            [x1, y1, z1 - h1 + h1off],
            [x1, y1, z1 + h1 + h1off],
            [x2, y2, z2 + h2 + h2off],
            [x2, y2, z2 - h2 + h2off],
        ];
        let inner = [
            [x1b, y1b, z1 - h1 + h1off],
            [x1b, y1b, z1 + h1 + h1off],
            [x2b, y2b, z2 + h2 + h2off],
            [x2b, y2b, z2 - h2 + h2off],
        ];
        let top = [
            [x2, y2, z2 + h2 + h2off],
            [x2b, y2b, z2 + h2 + h2off],
            [x1b, y1b, z1 + h1 + h1off],
            [x1, y1, z1 + h1 + h1off],
        ];
        let bottom = [
            [x1, y1, z1 - h1 + h1off],
            [x1b, y1b, z1 - h1 + h1off],
            [x2b, y2b, z2 - h2 + h2off],
            [x2, y2, z2 - h2 + h2off],
        ];

        if wire {
            for face in [outer, inner, top, bottom] {
                for i in 0..4 {
                    lines.push(face[i]);
                    lines.push(face[(i + 1) % 4]);
                }
            }
        } else {
            /* outer face */
            cw.push(([x1, y1, 0.0], outer[0]));
            cw.push(([x1, y1, 0.0], outer[1]));
            cw.push(([x2, y2, 0.0], outer[2]));
            cw.push(([x2, y2, 0.0], outer[3]));

            /* inner face */
            ccw.push(([-x1b, -y1b, 0.0], inner[0]));
            ccw.push(([-x1b, -y1b, 0.0], inner[1]));
            ccw.push(([-x2b, -y2b, 0.0], inner[2]));
            ccw.push(([-x2b, -y2b, 0.0], inner[3]));

            /* top face */
            let n = calc_normal(top[0], top[1], top[2]);
            for p in top {
                ccw.push((n, p));
            }

            /* bottom face */
            let n = calc_normal(bottom[0], bottom[1], bottom[2]);
            for p in bottom {
                ccw.push((n, p));
            }
        }

        x1 = x2;
        y1 = y2;
        x1b = x2b;
        y1b = y2b;
        z1 += z_inc;
        h1 = h2;
        h1off = h2off;
    }

    /* Trailing end-cap */
    if !wire && h2 > 0.0 {
        let n = [
            (th + std::f32::consts::FRAC_PI_2).cos(),
            (th + std::f32::consts::FRAC_PI_2).sin(),
            0.0,
        ];
        for p in [
            [x2, y2, z1 - h2 + h2off],
            [x2, y2, z1 + h2 + h2off],
            [x2b, y2b, z1 + h2 + h2off],
            [x2b, y2b, z1 - h2 + h2off],
        ] {
            cw.push((n, p));
        }
    }

    if wire {
        g.glx.begin(Shape::Lines);
        for p in lines {
            g.glx.vertex3f(p[0], p[1], p[2]);
        }
        g.glx.end();
        return;
    }
    for (facing, faces) in [(true, &cw), (false, &ccw)] {
        g.glx.front_face_cw(facing);
        g.glx.begin(Shape::Quads);
        for (n, p) in faces {
            g.glx.normal3f(n[0], n[1], n[2]);
            g.glx.vertex3f(p[0], p[1], p[2]);
        }
        g.glx.end();
    }
}

fn make_ladder(g: &mut Gl, dc: &Params, facetted: bool, wire: bool) {
    let max_th = dc.turns * std::f32::consts::PI * 2.0;
    let max_z = dc.turns * dc.turn_spacing;
    let mut z_inc = dc.bar_spacing;
    let th_inc = std::f32::consts::PI * 2.0 * (dc.bar_spacing / dc.turn_spacing);

    /* skip forward to center the bars in the helix... */
    let usable_th = max_th - dc.wall_taper;
    let usable_z = max_z / (max_th / usable_th);
    let mut nbars = (usable_z / dc.bar_spacing) as i32;

    /* always an odd number of bars */
    if nbars & 1 == 0 {
        nbars -= 1;
    }

    let used_z = (nbars - 1) as f32 * dc.bar_spacing;
    let pad_z = max_z - used_z;
    let pad_ratio = pad_z / max_z;

    let mut th = max_th * pad_ratio / 2.0;
    let mut z = -(max_z / 2.0) + (max_z * pad_ratio / 2.0);

    /* ##### WHYYYYYY */
    /* The image is not reflected across line y = -x and I don't know why. */
    th += std::f32::consts::PI * -0.035;
    z -= 0.08;

    if !dc.clockwise {
        z = -z;
        z_inc = -z_inc;
    }

    g.glx.front_face_cw(false);
    for _ in 0..nbars {
        let facets = (dc.bar_facets / if facetted { 14 } else { 1 }).max(3);
        let x = th.cos() * (1.0 - dc.wall_thickness);
        let y = th.sin() * (1.0 - dc.wall_thickness);
        tube(
            &mut g.glx,
            [x, y, z],
            [-x, -y, z],
            dc.bar_thickness,
            0.0,
            facets,
            true,
            true,
            wire,
        );
        z += z_inc;
        th += th_inc;
    }
}


//! The DNA Lounge sign: a double helix inside a gasket, in a picture frame,
//! turning over on itself. Every so often the helix shrinks away and the DNA
//! Pizza slice grows in its place, and every so often the whole thing is
//! drawn again as a wireframe over itself for a few seconds.
//!
//! Nothing here is animated in the usual sense. Everything that turns is a
//! *spinner*: a thing that is usually still and occasionally decides, with
//! some fixed probability a frame, to make exactly one full revolution and
//! stop. Its position is eased at both ends so it starts and finishes slowly,
//! and the two scene spinners are linked, so that when one starts the other
//! is given a turn to start as well.
//!
//! The gasket is the interesting shape. It is not modelled: it is a list of
//! forty-odd radius and angle pairs read off the real sign, interpolated
//! between at eight degrees a step, and then extruded. The outer rim's
//! normals are averaged with their neighbours' except where two faces meet at
//! more than about thirty-five degrees, which is what keeps the corners sharp
//! and the curves smooth without anyone having to say which is which.
//!
//! The pizza slice is a shape with holes in it, which upstream fills with the
//! GLU tessellator. There is no tessellator here, and upstream's own OpenGL
//! ES build has none either, so it carries the slice as a list of triangles
//! that its desktop build's tessellator produced once and had saved. That is
//! the list used here.


//! A game is who played it and when, the position it opens from in FEN, and
//! its moves. Each move is given twice: once in coordinate notation, which is
//! what the saver reads to know which piece goes where, and once in algebraic,
//! which is what it writes in the corner of the screen. Upstream carries a
//! move count alongside; here the list knows its own length.

/// One game, as upstream's `ChessGame` less the move count.
pub struct Game {
    /// The players and the year, and often the name the game goes by.
    pub desc: &'static str,
    /// The opening position, in Forsyth-Edwards notation: eight ranks from
    /// the eighth down, a letter per man and a digit per run of empty squares.
    pub fen: &'static str,
    /// Coordinate notation, then algebraic. `e7e8q` is a promotion.
    pub moves: &'static [(&'static str, &'static str)],
}

